"""Eye-to-hand extrinsic calibration for the fixed overhead camera.

Why not `cv2.calibrateHandEye`?  Because OpenCV 5.0.0 on this machine does not
export it (verified 2026-09-18: `dir(cv2)` has no `*HandEye*` symbol), and on top of
that the classic AX=XB formulation needs an accurate base<-gripper pose per sample,
which for an SO-101 means trusting nominal URDF link lengths plus servo backlash.
The board route below avoids both problems.

The route used here (and the reason it is the right one for this bench)
-----------------------------------------------------------------------
1. The ChArUco board is *fixed on the table* at a place we establish once
   (`T_base_board`).  Establishing that transform is the only manual step, and it
   can be done to ~1 mm with a touch probe or by lining the board up on marked
   table coordinates.
2. With the camera fixed and the board fixed, each captured frame yields
   `T_cam_board` directly from solvePnP.  No robot motion, no FK, no backlash.
3. Therefore  `T_base_cam = T_base_board @ inv(T_cam_board)`.
4. Averaging 20-50 frames beats a single frame: use a proper Karcher mean of the
   rotations (not an element-wise mean of rotation matrices, which is not a
   rotation) and the arithmetic mean of the translations.

The camera's pitch is *not* assumed.  It falls out of `T_base_cam`: run
`describe_mounting()` after calibration to read the resolved pitch and the measured
height above the table, and compare them with the tape-measure numbers.  A mismatch
means the board placement is wrong, not the camera.
"""
from __future__ import annotations

