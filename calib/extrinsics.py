# ------------------------------------------------------------- homogeneous math
def _T(R: np.ndarray, t: np.ndarray) -> np.ndarray:
    M = np.eye(4)
    M[:3, :3] = R
    M[:3, 3] = np.asarray(t, dtype=float).reshape(3)
    return M


def rvec_tvec_to_T(rvec: np.ndarray, tvec: np.ndarray) -> np.ndarray:
    R, _ = cv2.Rodrigues(np.asarray(rvec, dtype=float).reshape(3, 1))
    return _T(R, np.asarray(tvec, dtype=float).reshape(3))


def rotation_mean(rotations: list[np.ndarray]) -> np.ndarray:
    """Karcher/intrinsic mean of rotations via the standard iteration on SO(3).

    Iteration: R <- R * exp(mean_i log(R^T R_i)).

    Two details that are easy to get wrong and that `calib/selftest.py` pins down:

    * the residual must be R^T R_i, not R R_i^T.  The transposed form measures the
      rotation in the OPPOSITE direction, so the iteration walks away from the mean
      and settles near the antipode (a 10 deg pair averaged to 168 deg);
    * averaging rotation matrices element-wise is not the mean at all -- the result is
      generally not orthogonal, and re-orthonormalising once is not the same operation.
    """
    Rs = np.stack(rotations)
    R = Rs[0].copy()
    for _ in range(200):
        # residual[k] = R^T R_k  ->  elements (i, j) = sum_m R[m, i] R_k[m, j]
        dR = np.einsum("mi,nmj->nij", R, Rs)
        delta = np.mean([_so3_log(d) for d in dR], axis=0)
        if np.linalg.norm(delta) < 1e-12:
            break
        R = _nearest_rotation(R @ _so3_exp(delta))
    return R


def _so3_log(R: np.ndarray) -> np.ndarray:
    c = np.clip((np.trace(R) - 1.0) / 2.0, -1.0, 1.0)
    theta = float(np.arccos(c))
    if theta < 1e-10:
        return np.zeros(3)
    if abs(np.pi - theta) < 1e-6:
        A = (R + np.eye(3)) / 2.0
        axis = np.sqrt(np.clip(np.diag(A), 0, None))
        axis = axis / max(np.linalg.norm(axis), 1e-12)
        return axis * theta
    v = np.array([R[2, 1] - R[1, 2], R[0, 2] - R[2, 0], R[1, 0] - R[0, 1]])
    return v * (theta / (2.0 * np.sin(theta)))


def _so3_exp(w: np.ndarray) -> np.ndarray:
    theta = float(np.linalg.norm(w))
    if theta < 1e-12:
        return np.eye(3)
    k = w / theta
    K = np.array([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
    return np.eye(3) + np.sin(theta) * K + (1 - np.cos(theta)) * (K @ K)


# ------------------------------------------------------------------- board pose
def board_placement(
    origin_mm: tuple[float, float, float],
    yaw_deg: float = 0.0,
    pitch_deg: float = 0.0,
    roll_deg: float = 0.0,
    flip: bool = False,
) -> np.ndarray:
    """T_base_board: where the printed board sits on the table, in the arm frame.

    The board's own frame is the one OpenCV uses, and its exact convention matters:

        x_board : along the rows    (increasing column index)
        y_board : along the columns (increasing row index, i.e. toward the top of the
                                     printed image as generated by generateImage)
        z_board : out of the PRINTED face
        origin  : the first inner corner, one square in from the sheet's lower-left

    Getting this topology wrong flips the sign of the whole extrinsic solution, and the
    result still looks plausible.  `calib/selftest.py` asserts the topology explicitly.

    Orientation is built from the normal, not from Euler angles, so a flat board placed
    with yaw only comes out exactly right:

        z_board = Rz(yaw) . Rpitch(pitch) . n0     n0 = (0,0,1) for a flat board
        x_board = Rz(yaw) . (0,1,0)                the row direction on the table
        y_board = z_board x x_board

    `pitch_deg` tilts the board up about its row direction, which is how the operator
    presents a tilted board to a camera whose field of view cannot contain a large flat
    board (see the note in `calib/selftest.py`).  The row direction is taken in the
    world frame and then yawed, NOT rotated by `_rpy_rotation`, because that helper is
    ZYX (X applied first) and using it here silently tilts about the wrong axis.
    `flip=True` mounts the sheet rotated 180 deg about its normal, reversing the row and
    column directions while keeping the same face up.

    `origin_mm` is measured in the arm frame (origin at the shoulder-pan axis, x away
    from the arm, z up).  Measure it; a 5 mm error here rotates the whole solution.
    """
    yaw = np.radians(yaw_deg)
    Rz = np.array([[np.cos(yaw), -np.sin(yaw), 0.0],
                   [np.sin(yaw), np.cos(yaw), 0.0],
                   [0.0, 0.0, 1.0]])
    n_board = Rz @ np.array([0.0, 0.0, 1.0])
    x_board = Rz @ np.array([1.0, 0.0, 0.0])       # the row direction, before tilt
    tilt = np.radians(pitch_deg)
    if abs(tilt) > 1e-12:
        n_board = n_board * np.cos(tilt) + x_board * np.sin(tilt)
    if flip:
        n_board, x_board = -n_board, -x_board
    x_board = x_board - (x_board @ n_board) * n_board
    x_board = x_board / np.linalg.norm(x_board)
    y_board = np.cross(n_board, x_board)
    R = np.column_stack([x_board, y_board, n_board])
    if abs(roll_deg) > 1e-12:
        spin = np.radians(roll_deg)
        c, s = np.cos(spin), np.sin(spin)
        R = R @ np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]])
    R = _nearest_rotation(R)
    return _T(R, np.asarray(origin_mm, dtype=float) / 1000.0)


def _rpy_rotation(roll_deg: float, pitch_deg: float, yaw_deg: float) -> np.ndarray:
    r, p, y = np.radians([roll_deg, pitch_deg, yaw_deg])
    Rx = np.array([[1, 0, 0], [0, np.cos(r), -np.sin(r)], [0, np.sin(r), np.cos(r)]])
    Ry = np.array([[np.cos(p), 0, np.sin(p)], [0, 1, 0], [-np.sin(p), 0, np.cos(p)]])
    Rz = np.array([[np.cos(y), -np.sin(y), 0], [np.sin(y), np.cos(y), 0], [0, 0, 1]])
    return Rz @ Ry @ Rx


def _nearest_rotation(R: np.ndarray) -> np.ndarray:
    """Project onto SO(3): removes accumulated numeric drift and guarantees det = +1."""
    u, _s, vt = np.linalg.svd(R)
    out = u @ vt
    if np.linalg.det(out) < 0:
        u[:, -1] *= -1
        out = u @ vt
    return out


def look_at(eye: np.ndarray, forward: np.ndarray, image_up_hint: np.ndarray,
            *, as_cam_from_base: bool = False) -> np.ndarray:
    """A camera pose for a viewing direction, in one of two explicit conventions.

    A camera frame is right-handed: x_cam = image right, y_cam = image DOWN,
    z_cam = optical axis.  Two traps, both of which still give det = +1 and orthogonal
    columns, and a camera pointing somewhere else entirely:

      1. x_cam = z_cam x up, NOT up x z_cam;
      2. `up` must not be parallel to the viewing direction.

    Both are checked, so neither can survive silently.

    The returned matrix is either

        T_base_cam  (default):      p_base = R p_cam + eye
        T_cam_base  (as_cam_from_base=True):  p_cam = R p_base + t, t = -R^T eye

    Both are returned from this one function because building them in two places is how
    the two conventions drift apart: an earlier version paired a `t = eye` pose with the
    generic `invert()` helper, and the pair silently stopped being inverses of each other
    (R_base_cam @ eye + t_cam_base != 0).  The round trip was still exact -- the error
    cancelled between the two mismatched matrices -- so every consistency check on the
    composed path passed while the intermediate quantities were wrong, which is exactly
    the kind of bug that produces a plausible-looking 70 mm position error.
    """
    z_cam = np.asarray(forward, dtype=float)
    z_cam = z_cam / np.linalg.norm(z_cam)
    up = np.asarray(image_up_hint, dtype=float)
    up = up / np.linalg.norm(up)
    x_cam = np.cross(z_cam, up)
    if np.linalg.norm(x_cam) < 1e-6:
        raise ValueError("image_up_hint is parallel to the viewing direction")
    x_cam = x_cam / np.linalg.norm(x_cam)
    y_cam = np.cross(z_cam, x_cam)
    R = np.column_stack([x_cam, y_cam, z_cam])          # camera -> base
    if not np.allclose(R @ R.T, np.eye(3), atol=1e-9) or np.linalg.det(R) < 0:
        raise ValueError("constructed camera frame is not a proper rotation")
    eye = np.asarray(eye, dtype=float).reshape(3)

    T = np.eye(4)
    if as_cam_from_base:
        T[:3, :3] = R.T
        T[:3, 3] = -R.T @ eye
    else:
        T[:3, :3] = R
        T[:3, 3] = eye
    return T


def framing_check(
    spec: BoardSpec,
    board_origin_mm: tuple[float, float, float],
    board_yaw_deg: float,
    board_pitch_deg: float,
    table_z_mm: float,
    camera_forward_mm: float,
    camera_height_above_table_mm: float,
    camera_pitch_deg: float,
    image_size: tuple[int, int] = (640, 480),
    K: np.ndarray | None = None,
) -> dict:
    """Will this board be visible to this camera?  Answer it before spending a session.

    Built from MOUNT parameters (where the camera is, how high, how far it pitches) rather
    than from a full 6-DOF pose matrix.  That is deliberate: three separate bugs in this
    project came from hand-building a camera pose, because a wrong cross-product order
    still yields an orthogonal matrix with det = +1 and a camera looking the wrong way.
    Mount parameters have no handedness to get wrong.

    Why it matters: the overhead camera is ~610 mm above the table and pitched ~16 deg off
    vertical, so its 43.4 deg vertical field of view covers only about 460 mm of table
    depth, and a board lying flat is seen at ~74 deg incidence (~3.6x foreshortening).  A
    300 x 390 mm board cannot be framed in this view at all, and a board nearer than the
    visible band runs off the bottom of the image.
    """
    if K is None:
        K = np.array([[603.7, 0.0, image_size[0] / 2.0],
                      [0.0, 602.4, image_size[1] / 2.0], [0.0, 0.0, 1.0]])
    eye = np.array([camera_forward_mm, 0.0,
                    table_z_mm + camera_height_above_table_mm]) / 1000.0
    fwd = np.array([-np.sin(np.radians(camera_pitch_deg)), 0.0,
                    -np.cos(np.radians(camera_pitch_deg))])
    T_base_cam = look_at(eye, fwd, np.array([0.0, -1.0, 0.0]))
    T_cam_base = look_at(eye, fwd, np.array([0.0, -1.0, 0.0]), as_cam_from_base=True)

    T_base_board = board_placement(board_origin_mm, yaw_deg=board_yaw_deg,
                                   pitch_deg=board_pitch_deg)
    board_w_mm = spec.squares_x * spec.square_m * 1000.0
    board_h_mm = spec.squares_y * spec.square_m * 1000.0
    corners = np.array([
        [0.0, 0.0, 0.0], [board_w_mm / 1000.0, 0.0, 0.0],
        [board_w_mm / 1000.0, board_h_mm / 1000.0, 0.0], [0.0, board_h_mm / 1000.0, 0.0]])
    homogeneous = (T_cam_base @ T_base_board @
                   np.hstack([corners, np.ones((4, 1))]).T).T
    cam_pts = homogeneous[:, :3]

    ok = bool(np.all(cam_pts[:, 2] > 0.05))
    inside = False
    uvs = None
    if ok:
        uvs = np.array([(K[0, 0] * p[0] / p[2] + K[0, 2], K[1, 1] * p[1] / p[2] + K[1, 2])
                        for p in cam_pts])
        inside = bool(uvs[:, 0].min() >= 2 and uvs[:, 0].max() <= image_size[0] - 3
                      and uvs[:, 1].min() >= 2 and uvs[:, 1].max() <= image_size[1] - 3)

    return {
        "board_in_front_of_camera": ok,
        "board_fully_inside_frame": inside,
        "board_pixel_bbox": None if uvs is None else
        [round(float(uvs[:, 0].min()), 1), round(float(uvs[:, 1].min()), 1),
         round(float(uvs[:, 0].max()), 1), round(float(uvs[:, 1].max()), 1)],
        "board_range_mm": [round(float(cam_pts[:, 2].min()) * 1000, 1),
                           round(float(cam_pts[:, 2].max()) * 1000, 1)],
        "visible_table_band": visible_table_band(T_cam_base, table_z_mm, image_size, K),
        "verdict": ("ok" if ok and inside else
                    "board runs outside the frame; move it further from the arm, tilt it "
                    "toward the camera, use a smaller board, or raise the camera"),
    }


def visible_table_band(T_cam_base: np.ndarray, table_z_mm: float = -127.4,
                       image_size: tuple[int, int] = (640, 480),
                       K: np.ndarray | None = None, step_mm: float = 10.0) -> dict:
    """The strip of table the camera can actually see, in the arm frame.

    `T_cam_base` is camera-from-base (the inverse of T_base_cam).  Use it to place the
    board: its near corner must be beyond `x_range_mm[0]`, or it falls off the bottom of
    the image.
    """
    if K is None:
        K = np.array([[603.7, 0.0, image_size[0] / 2.0],
                      [0.0, 602.4, image_size[1] / 2.0], [0.0, 0.0, 1.0]])
    xs, ys = [], []
    for x in np.arange(-0.2, 1.4, step_mm / 1000.0):
        for y in np.arange(-0.7, 0.7, step_mm / 1000.0):
            p_base = np.array([x, y, table_z_mm / 1000.0])
            p_cam = T_cam_base[:3, :3] @ p_base + T_cam_base[:3, 3]
            if p_cam[2] <= 0.05:
                continue
            u = K[0, 0] * p_cam[0] / p_cam[2] + K[0, 2]
            v = K[1, 1] * p_cam[1] / p_cam[2] + K[1, 2]
            if 2 <= u <= image_size[0] - 3 and 2 <= v <= image_size[1] - 3:
                xs.append(x)
                ys.append(y)
    if not xs:
        return {"visible": False}
    return {
        "visible": True,
        "x_range_mm": [round(min(xs) * 1000, 1), round(max(xs) * 1000, 1)],
        "y_range_mm": [round(min(ys) * 1000, 1), round(max(ys) * 1000, 1)],
        "depth_of_visible_band_mm": round((max(xs) - min(xs)) * 1000, 1),
    }


# --------------------------------------------------------------- frame capture
def detect_board_in_frame(
    gray: np.ndarray, spec: BoardSpec, K: np.ndarray, dist: np.ndarray
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray] | None:
    detector = cv2.aruco.CharucoDetector(spec.board)
    ch_corners, ch_ids, m_corners, m_ids = detector.detectBoard(gray)
    if ch_corners is None or ch_ids is None or len(ch_ids) < 8:
        return None
    objp, imgp = spec.board.matchImagePoints(ch_corners, ch_ids)
    if objp is None or len(objp) < 8:
        return None
    ok, rvec, tvec = cv2.solvePnP(objp, imgp, K, dist, flags=cv2.SOLVEPNP_ITERATIVE)
    if not ok:
        return None
    return rvec, tvec, objp, imgp


def calib_from_frames(
    frames: list[np.ndarray],
    T_base_board: np.ndarray,
    *,
    spec: BoardSpec = TABLE_BOARD,
    K: np.ndarray | None = None,
    dist: np.ndarray | None = None,
) -> dict:
    """Solve the extrinsic from captured frames.  `frames` are grayscale images; K and
    dist come from the intrinsics calibration (pass them explicitly)."""
    if K is None or dist is None:
        raise ValueError("pass K and dist (from the intrinsics calibration)")

    rotations, translations, rms_list = [], [], []
    for gray in frames:
        det = detect_board_in_frame(gray, spec, K, dist)
        if det is None:
            continue
        rvec, tvec, objp, imgp = det
        proj, _ = cv2.projectPoints(objp, rvec, tvec, K, dist)
        rms_list.append(float(np.linalg.norm(proj.reshape(-1, 2) - imgp.reshape(-1, 2), axis=1).mean()))
        T_cam_board = rvec_tvec_to_T(rvec, tvec)
        # T_base_cam_i = T_base_board @ inv(T_cam_board)
        T_base_cam_i = T_base_board @ invert(T_cam_board)
        rotations.append(T_base_cam_i[:3, :3])
        translations.append(T_base_cam_i[:3, 3])

    if len(rotations) < 3:
        raise RuntimeError(f"only {len(rotations)} usable frames; need at least 3, aim for 20-50")

    R_mean = rotation_mean(rotations)
    t_mean = np.mean(np.stack(translations), axis=0)
    T_base_cam = _T(R_mean, t_mean)

    # spread of the individual solutions = a direct measure of calibration noise
    t_spread = float(np.max(np.linalg.norm(np.stack(translations) - t_mean, axis=1)) * 1000)
    return {
        "T_base_cam": T_base_cam,
        "n_frames": len(rotations),
        "solvepnp_rms_px": round(float(np.mean(rms_list)), 4),
        "translation_spread_mm": round(t_spread, 2),
        "rotation_spread_deg": round(float(np.degrees(np.max(
            [np.linalg.norm(_so3_log(R_mean.T @ R)) for R in rotations]))), 3),
    }


# ------------------------------------------------------------- interpretation
def describe_mounting(T_base_cam: np.ndarray, table_z_mm: float = -127.4) -> dict:
    """Resolve the mounting parameters out of the calibration, without assuming them.

    Conventions: the camera optical frame is x right, y down, z forward.  A camera
    looking straight down has its optical z pointing down, i.e. -z of the arm frame.

    `table_z_mm` is the table surface in the arm frame.  The DS101 arm frame has its
    origin at the shoulder-pan axis, which sits about 127.4 mm above the table, so the
    table is at z = -127.4 mm; the default reflects that.

    Height is reported as a magnitude: the sign of a "height" carries no information
    and getting it wrong (the first version of this function subtracted the table z,
    producing -610 mm for a camera 610 mm above the table) makes the check look failed
    when the calibration is fine.
    """
    R = T_base_cam[:3, :3]
    t = T_base_cam[:3, 3]
    z_axis_base = R @ np.array([0.0, 0.0, 1.0])   # optical axis in the arm frame
    pitch_from_nadir_deg = float(np.degrees(np.arccos(np.clip(-z_axis_base[2], -1.0, 1.0))))
    forward_mm = float(t[0] * 1000)
    lateral_mm = float(t[1] * 1000)
    height_mm = float(abs(t[2] - table_z_mm / 1000.0) * 1000)
    return {
        "camera_position_mm": [round(float(v) * 1000, 1) for v in t],
        "camera_forward_from_base_mm": round(forward_mm, 1),
        "camera_lateral_offset_mm": round(lateral_mm, 1),
        "camera_height_above_table_mm": round(height_mm, 1),
        "pitch_from_nadir_deg": round(pitch_from_nadir_deg, 2),
        "optical_axis_in_base": [round(float(v), 4) for v in z_axis_base],
        "note": "compare these with the tape measure; >10 mm or >2 deg disagreement means "
                "the board placement (T_base_board) is wrong",
    }


def project_to_base(
    u: float, v: float, depth_m: float, K: np.ndarray, T_base_cam: np.ndarray
) -> np.ndarray:
    """Pixel + aligned depth -> point in the arm frame.  The core of 'click a pixel, get a target'."""
    z = float(depth_m)
    p_cam = np.array([(u - K[0, 2]) * z / K[0, 0], (v - K[1, 2]) * z / K[1, 1], z])
    return transform_points(T_base_cam, p_cam.reshape(1, 3))[0]


def table_plane_in_base(
    normal_cam: np.ndarray, point_cam: np.ndarray, T_base_cam: np.ndarray
) -> dict:
    """Transform the RANSAC table plane into the arm frame, for a physical sanity check."""
    n_base = T_base_cam[:3, :3] @ np.asarray(normal_cam, dtype=float)
    p_base = transform_points(T_base_cam, np.asarray(point_cam, dtype=float).reshape(1, 3))[0]
    cam = T_base_cam[:3, 3]
    return {
        "normal_base": [round(float(x), 4) for x in n_base],
        "point_base_mm": [round(float(x) * 1000, 1) for x in p_base],
        "camera_height_above_table_mm": round(float(abs((cam - p_base) @ n_base) * 1000), 1),
        "tilt_of_table_from_horizontal_deg": round(
            float(np.degrees(np.arccos(np.clip(abs(n_base[2]), -1.0, 1.0)))), 2),
    }


def save(result: dict, T_base_board: np.ndarray, path: str | Path, *, camera: str = "overhead_d435") -> None:
    payload = {
        "camera": camera,
        "T_base_cam": result["T_base_cam"].tolist(),
        "T_base_board": T_base_board.tolist(),
        "n_frames": result["n_frames"],
        "solvepnp_rms_px": result["solvepnp_rms_px"],
        "translation_spread_mm": result["translation_spread_mm"],
        "rotation_spread_deg": result["rotation_spread_deg"],
        "mounting": describe_mounting(result["T_base_cam"]),
    }
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(payload, indent=2), encoding="utf-8")


